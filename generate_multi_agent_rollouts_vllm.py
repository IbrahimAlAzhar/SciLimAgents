def consolidate_and_save(all_paper_records):
    with open(OUTPUT_FULL_JSON, "w") as f:
        json.dump(all_paper_records, f, indent=2)

    worker, leader, master = [], [], []
    for paper in all_paper_records:
        for rollout in paper.get("rollouts", []):
            for s in rollout.get("samples", []):
                role = s.get("agent_role")
                if   role == "worker": worker.append(s)
                elif role == "leader": leader.append(s)
                elif role == "master": master.append(s)

    with open(OUTPUT_WORKER_JSON, "w") as f: json.dump(worker, f, indent=2)
    with open(OUTPUT_LEADER_JSON, "w") as f: json.dump(leader, f, indent=2)
    with open(OUTPUT_MASTER_JSON, "w") as f: json.dump(master, f, indent=2)

    print(f"  workers:{len(worker)} leader:{len(leader)} master:{len(master)}")

def wait_for_server(max_wait=1200):
    """Block until the vLLM server answers /models."""
    t0 = time.time()
    while time.time() - t0 < max_wait:
        try:
            models = [m.id for m in _client.models.list().data]
            print(f"vLLM ready. Served models: {models}")
            for name in {WORKER_MODEL, LEADER_MODEL, MASTER_MODEL}:
                if name not in models:
                    print(f"[WARN] '{name}' not in served models — requests will 404.")
            return True
        except Exception:
            time.sleep(10)
    raise RuntimeError(f"vLLM at {VLLM_BASE_URL} never became ready.")

