"""
generate_multi_agent_rollouts_vllm.py
====================

Rollout generation ONLY — multi-agent limitation extraction (3-HOP + 4-MODE),
generated by a LOCAL **Qwen3-4B** served through a vLLM OpenAI-compatible server.

This is a drop-in replacement for `rollout_gpt.py`:
  * autogen + GPT-4o-mini  ->  plain `openai` client pointed at vLLM
  * tiktoken               ->  the model's own HF tokenizer (exact budgeting)
  * sequential workers     ->  ThreadPoolExecutor (vLLM batches the requests)
  * Qwen3 thinking mode DISABLED (`enable_thinking=false`) so outputs are the
    clean bullet lists the stepwise scorer parses and you train on.

It computes NO rewards. Scoring stays with `select_data_stepwise_process_reward.py`
(GPT-4o-mini reward/judge), which reads `rollout_data_full.json`.

The output JSON schema is byte-for-byte compatible with the old script:
  - rollout_data_full.json     (feed this to the stepwise scorer)
  - rollout_data_worker.json / _leader.json / _master.json

Per paper we run N rollouts (default 4), each bound 1:1 to an EXPLORATION MODE
and a sampling config:

    rollout 0  ->  strict_grounding   (T=0.7, seed=42)
    rollout 1  ->  critique_heavy     (T=0.9, seed=123)
    rollout 2  ->  retrieval_heavy    (T=1.1, seed=456)
    rollout 3  ->  search_repair      (T=0.5, seed=789)

Within every rollout, each of the 6 specialist workers runs a 3-HOP chain:
    HOP 1 SEARCH -> HOP 2 QUERY -> HOP 3 DRAFT

Everything is env-overridable so the PBS script can drive it.

Run (server must already be up):
    VLLM_BASE_URL=http://127.0.0.1:8000/v1 SERVED_MODEL_NAME=student \
    python generate_multi_agent_rollouts_vllm.py
"""

