def _count_tokens(text):
    tok = _tokenizer()
    try:
        return len(tok.encode(text, add_special_tokens=False))
    except TypeError:
        return len(tok.encode(text))

def llm_call(system_prompt, user_message, sampling_config, max_tokens=1024,
             model=None, temperature_override=None):
    """One chat completion against the vLLM OpenAI server (Qwen3-4B).

    - `enable_thinking` is forced off by default (Qwen3 chat-template kwarg).
    - Prompt is shrunk if system+user would overflow the context window.
    - Retries with exponential backoff on transient server errors.
    """
    model = model or SERVED_MODEL_NAME

    # --- context safety: never let prompt + max_tokens exceed the window ---
    budget = MAX_MODEL_LEN - max_tokens - 256          # 256 = chat-template overhead
    n_sys, n_usr = _count_tokens(system_prompt), _count_tokens(user_message)
    if n_sys + n_usr > budget:
        # shrink the system prompt first (it carries the paper), then the user msg
        sys_budget = max(512, budget - n_usr)
        system_prompt = truncate_text_to_tokens(system_prompt, sys_budget)
        n_sys = _count_tokens(system_prompt)
        if n_sys + n_usr > budget:
            user_message = truncate_text_to_tokens(user_message, max(256, budget - n_sys))

    kwargs = {
        "model": model,
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_message},
        ],
        "temperature": (sampling_config["temperature"] if temperature_override is None
                        else temperature_override),
        "top_p": sampling_config.get("top_p", 1.0),
        "max_tokens": max_tokens,
        "seed": sampling_config.get("seed", 42),
        "extra_body": {
            "chat_template_kwargs": {"enable_thinking": ENABLE_THINKING},
            "repetition_penalty": 1.05,
        },
    }

    last_err = None
    for attempt in range(MAX_RETRIES):
        try:
            resp = _client.chat.completions.create(**kwargs)
            out = resp.choices[0].message.content or ""
            if not ENABLE_THINKING:
                out = re.sub(r"<think>.*?</think>", " ", out, flags=re.DOTALL | re.IGNORECASE)
            return out.strip()
        except Exception as e:
            last_err = e
            sleep = min(30, (2 ** attempt) + random.random())
            print(f"  [retry {attempt+1}/{MAX_RETRIES}] {type(e).__name__}: {e} — sleeping {sleep:.1f}s")
            time.sleep(sleep)
    print(f"  [ERROR] llm_call failed after {MAX_RETRIES} tries: {last_err}")
    return ""

