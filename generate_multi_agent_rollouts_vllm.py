def run_pipeline():
    print("=" * 66)
    print("QWEN3-4B ROLLOUT GENERATION (vLLM)")
    print("=" * 66)
    print(f"model dir : {MODEL_PATH}")
    print(f"vllm url  : {VLLM_BASE_URL}")
    print(f"served    : worker={WORKER_MODEL} leader={LEADER_MODEL} master={MASTER_MODEL}")
    print(f"thinking  : {'ON' if ENABLE_THINKING else 'OFF'}")
    print(f"out dir   : {OUTPUT_DIR}")

    wait_for_server()

    print(f"Loading CSV: {INPUT_CSV}")
    df_full = pd.read_csv(INPUT_CSV)
    row_end = ROW_END if ROW_END is not None else len(df_full)
    df = df_full.iloc[ROW_START:row_end].copy().reset_index(drop=True)
    print(f"Processing the configured slice with {len(ROLLOUT_CONFIGS)} mode-rollouts per paper.")

    all_paper_records = []
    existing_checkpoints = set(os.listdir(CHECKPOINT_DIR))

    for local_i in tqdm(range(len(df)), desc="Papers"):
        global_i = ROW_START + local_i
        ckpt_name = f"paper_{global_i:05d}.json"
        ckpt_path = os.path.join(CHECKPOINT_DIR, ckpt_name)

        if ckpt_name in existing_checkpoints:
            try:
                with open(ckpt_path, "r") as f:
                    cached = json.load(f)
                has_real = any(len(r.get("samples", [])) > 0 for r in cached.get("rollouts", []))
                if has_real:
                    all_paper_records.append(cached)
                    continue
                print(f"[RETRY] paper {global_i}: checkpoint empty, re-running")
            except Exception:
                pass

        row = df.iloc[local_i]
        paper_text   = str(row.get(INPUT_COL, ""))
        ground_truth = str(row.get(GT_COL, ""))
        citation_raw = row.get(CITATION_COL, "") if CITATION_COL in df.columns else ""

        paper_text    = truncate_text_to_tokens(paper_text, PAPER_TOKEN_LIMIT)
        evidence_text = truncate_text_to_tokens(build_evidence_tagged(paper_text), PAPER_TOKEN_LIMIT)
        citation_text = truncate_text_to_tokens(
            extract_intro_and_abstract(citation_raw, top_k=8), CITATION_TOKEN_LIMIT)

        if len(paper_text) < 100:
            print(f"[SKIP] paper {global_i}: text too short")
            continue

        paper_record = {
            "paper_idx": int(global_i),
            "paper_text": paper_text,
            "citation_text": citation_text,
            "ground_truth": ground_truth,
            "rollouts": [],
        }

        for rc in ROLLOUT_CONFIGS:
            print(f"  -> paper {global_i} | rollout {rc['rollout_id']} | mode={rc['mode']} "
                  f"(T={rc['temperature']}, seed={rc['seed']})")
            t0 = time.time()
            try:
                result = execute_single_rollout(
                    global_i, paper_text, evidence_text, citation_text, ground_truth, rc
                )
                paper_record["rollouts"].append({
                    "rollout_id": rc["rollout_id"],
                    "rollout_config": rc,
                    "mode": result["mode"],
                    "samples": result["samples"],
                    "final_master_output": result["final_master_output"],
                    "worker_final": result["worker_final"],
                })
                print(f"     done in {time.time()-t0:.1f}s "
                      f"({len(result['samples'])} samples)")
            except Exception as e:
                print(f"  [ERROR] paper {global_i} rollout {rc['rollout_id']}: {e}")
                paper_record["rollouts"].append({
                    "rollout_id": rc["rollout_id"], "rollout_config": rc, "mode": rc["mode"],
                    "error": str(e), "samples": [], "final_master_output": "", "worker_final": {},
                })

        with open(ckpt_path, "w") as f:
            json.dump(paper_record, f, indent=2)
        all_paper_records.append(paper_record)

        if (local_i + 1) % 5 == 0:
            consolidate_and_save(all_paper_records)

    consolidate_and_save(all_paper_records)
    print(f"\nDone (rollouts only). Outputs in: {OUTPUT_DIR}")
    print("Next: python select_data_stepwise_process_reward.py --rollout_json "
          f"{OUTPUT_FULL_JSON}")

if __name__ == "__main__":
    run_pipeline()