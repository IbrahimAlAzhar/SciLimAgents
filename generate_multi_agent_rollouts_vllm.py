# 7. ONE ROLLOUT (mode-driven pipeline, NO rewards)
# ==========================================

def execute_single_rollout(paper_idx, paper_text, evidence_text, citation_text,
                           ground_truth, rollout_config):
    mode = rollout_config["mode"]
    action = MODE_ACTION_CONFIG[mode]

    worker_paper = evidence_text if action.get("cite_evidence_ids") else paper_text
    retrieval_context = ""
    if action.get("use_retrieval"):
        retrieval_context = truncate_text_to_tokens(
            citation_text, min(CITATION_TOKEN_LIMIT, action.get("retrieval_top_k", 8) * 500)
        )

    leader_sys = get_leader_system_prompt()
    master_sys = get_master_system_prompt()

    rc_meta = {k: rollout_config[k] for k in ("temperature", "top_p", "seed", "mode")}
    ridx = rollout_config["rollout_id"]
    leader_cfg = LEADER_CONFIGS[ridx % len(LEADER_CONFIGS)]
    master_cfg = MASTER_CONFIGS[ridx % len(MASTER_CONFIGS)]
    leader_meta = {**{k: leader_cfg[k] for k in ("temperature", "top_p", "seed")}, "mode": mode}
    master_meta = {**{k: master_cfg[k] for k in ("temperature", "top_p", "seed")}, "mode": mode}

    # ---------- WORKERS in parallel (vLLM batches the concurrent requests) ----------
    samples = []
    all_worker_final = {}
    with ThreadPoolExecutor(max_workers=max(1, N_WORKER_THREADS)) as ex:
        futures = [
            ex.submit(run_worker_full, wspec, worker_paper, mode, action, rollout_config,
                      retrieval_context, leader_sys, leader_cfg, paper_idx,
                      ground_truth, rc_meta, leader_meta)
            for wspec in WORKER_CONFIGS
        ]
        results = [f.result() for f in futures]

    # keep a deterministic order (worker registry order) regardless of finish order
    order = {w[0]: i for i, w in enumerate(WORKER_CONFIGS)}
    results.sort(key=lambda t: order[t[0]])
    for wname, wfinal, wsamples in results:
        all_worker_final[wname] = wfinal
        samples.extend(wsamples)

    # ---------- LEADER HANDOFF ----------
    leader_bundle_user = (
        "You have collected revised outputs from all 6 specialist workers. Produce the "
        "MODE B handoff to the Master Agent. Here are the 6 outputs:\n\n"
        + "\n\n".join([f"### {w}:\n{o}" for w, o in all_worker_final.items()])
    )
    leader_handoff = llm_call(leader_sys, leader_bundle_user, leader_cfg,
                              max_tokens=1800, model=LEADER_MODEL)
    samples.append({
        "paper_idx": paper_idx, "rollout_id": rollout_config["rollout_id"],
        "rollout_config": leader_meta,
        "agent_role": "leader", "agent_name": "Leader_Agent",
        "turn_type": "handoff_to_master", "mode": mode,
        "input_messages": [
            {"role": "system", "content": leader_sys},
            {"role": "user", "content": leader_bundle_user},
        ],
        "output": leader_handoff, "ground_truth": ground_truth,
    })

    # ---------- MASTER ----------
    master_sys_eff = master_sys
    if APPLY_MASTER_TOT:
        master_sys_eff = master_sys + (
            "\n\n[TREE-OF-THOUGHT + SELF-REPAIR] Internally explore a few distinct "
            "consolidation paths (different groupings / prioritizations), pick the "
            "strongest, then self-critique it once and repair any weak, redundant, or "
            "poorly-grounded points before returning the FINAL list only."
        )
    master_output = llm_call(master_sys_eff, leader_handoff, master_cfg,
                             max_tokens=1800, model=MASTER_MODEL)
    samples.append({
        "paper_idx": paper_idx, "rollout_id": rollout_config["rollout_id"],
        "rollout_config": master_meta,
        "agent_role": "master", "agent_name": "Master_Agent",
        "turn_type": "synthesis", "mode": mode,
        "input_messages": [
            {"role": "system", "content": master_sys_eff},
            {"role": "user", "content": leader_handoff},
        ],
        "output": master_output, "ground_truth": ground_truth,
    })

    return {
        "mode": mode,
        "samples": samples,
        "final_master_output": master_output,
        "worker_final": all_worker_final,
    }

