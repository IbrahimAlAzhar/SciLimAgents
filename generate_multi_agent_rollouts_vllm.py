_TOK = None
_TOK_LOCK = threading.Lock()

def _tokenizer():
    """Qwen3 tokenizer from the local model dir (falls back to tiktoken)."""
    global _TOK
    if _TOK is None:
        with _TOK_LOCK:
            if _TOK is None:
                try:
                    from transformers import AutoTokenizer
                    _TOK = AutoTokenizer.from_pretrained(MODEL_PATH, trust_remote_code=True)
                except Exception as e:
                    print(f"[WARN] HF tokenizer unavailable ({e}); using tiktoken cl100k_base.")
                    import tiktoken
                    _TOK = tiktoken.get_encoding("cl100k_base")
    return _TOK

def truncate_text_to_tokens(text, max_tokens):
    if not text:
        return ""
    tok = _tokenizer()
    try:
        ids = tok.encode(text, add_special_tokens=False)
    except TypeError:            # tiktoken
        ids = tok.encode(text)
    if len(ids) <= max_tokens:
        return text
    return tok.decode(ids[:max_tokens]) + " ... [TRUNCATED]"

def clean_text_detailed(text):
    if pd.isna(text) or text is None:
        return ""
    text = str(text).replace("\n", " ")
    text = re.sub(r"\S+\s+et\s+al\.?", "", text, flags=re.IGNORECASE)
    text = re.sub(r"\d+", "", text)
    return re.sub(r"\s+", " ", text).strip()

def build_evidence_tagged(paper_text):
    """Tag sentences with [E#] IDs so agents can cite evidence IDs in strict mode."""
    chunks = re.split(r"(?<=[.!?])\s+", paper_text)
    tagged, n = [], 0
    for c in chunks:
        c = c.strip()
        if not c:
            continue
        n += 1
        tagged.append(f"[E{n}] {c}")
    return " ".join(tagged)

def extract_intro_and_abstract(cited_entry, top_k=8):
    """Parse the cited-papers column into a compact retrieval context (top_k papers)."""
    if cited_entry is None or (isinstance(cited_entry, float) and pd.isna(cited_entry)):
        return ""
    try:
        parsed = ast.literal_eval(cited_entry) if isinstance(cited_entry, str) else cited_entry
    except Exception:
        return ""
    if not isinstance(parsed, dict):
        return ""
    processed = []
    for idx, (pid, data) in enumerate(parsed.items(), 1):
        if idx > top_k:
            break
        if not isinstance(data, dict):
            continue
        intro = ""
        for sec in data.get("sections", []) or []:
            if "introduction" in str(sec.get("heading", "")).lower():
                intro = sec.get("text", "")
                break
        t_clean = clean_text_detailed(data.get("title", ""))
        a_clean = clean_text_detailed(data.get("abstractText") or data.get("abstract"))
        i_clean = clean_text_detailed(intro)
        if t_clean or a_clean or i_clean:
            processed.append(
                f"Paper{idx}_Title: {t_clean}\nPaper{idx}_Abstract: {a_clean}\n"
                f"Paper{idx}_Introduction: {i_clean}"
            )
    return "\n\n".join(processed)

